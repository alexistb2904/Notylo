const tables: Record<Locale, Record<MessageKey, string>> = { en, fr };

export function detectLocale(languages: readonly string[] = browserLanguages()): Locale {
  for (const language of languages) {
    const base = language.trim().toLowerCase().split(/[-_]/, 1)[0];
    if (base === "fr" || base === "en") return base;
  }
  return "en";
}

function browserLanguages(): readonly string[] {
  if (typeof navigator === "undefined") return [];
  if (navigator.languages?.length) return navigator.languages;
  return navigator.language ? [navigator.language] : [];
}

export const locale: Locale = detectLocale();
export const intlLocale = locale === "fr" ? "fr-FR" : "en-US";

export function t(key: MessageKey, values: Readonly<Record<string, string | number>> = {}): string {
  const template = tables[locale][key] ?? en[key];
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

export function formatDate(
  value: Date | string | number,
  options: Intl.DateTimeFormatOptions = { dateStyle: "medium" }
): string {
  return new Intl.DateTimeFormat(intlLocale, options).format(
    value instanceof Date ? value : new Date(value)
  );
}

export function formatNumber(
  value: number,
  options?: Intl.NumberFormatOptions
): string {
  return new Intl.NumberFormat(intlLocale, options).format(value);
}

export function applyDocumentLocale(): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
  if (description) description.content = t("meta.description");
}

const remoteErrorEnglish: Readonly<Record<string, string>> = {
  "Une erreur est survenue.": en["common.errorGeneric"],
  "Le service cloud est indisponible. Vos cahiers locaux restent accessibles.": en["api.cloudUnavailable"],
  "Impossible de récupérer une pièce jointe cloud.": en["api.attachmentUnavailable"],
  "Le stockage cloud est indisponible. La copie locale reste accessible.": en["api.storageUnavailable"],
  "Les passkeys ne sont pas prises en charge par ce navigateur.": en["auth.passkeysUnsupported"]
};

export function localizeRemoteError(message: string | undefined, fallback: MessageKey = "common.errorGeneric"): string {
  if (!message) return t(fallback);
  if (locale === "fr") return message;
  return remoteErrorEnglish[message] ?? t(fallback);
}
